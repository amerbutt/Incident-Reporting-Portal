// Helper to expand and seed 120+ additional dynamic historical incidents for high-density analytics
export function getGeneratedIncidentDataset(): Incident[] {
  const dataset: Incident[] = [...INITIAL_MOCK_INCIDENTS];
  const subSectors = ['D-12/1', 'D-12/2', 'D-12/3', 'D-12/4'];
  const streets = ['Street 1', 'Street 3', 'Street 5', 'Street 7', 'Street 9', 'Street 11', 'Street 15', 'Street 22', 'Street 28', 'Main Double Road'];
  const typesByCategory: Record<IncidentCategory, string[]> = {
    Security: ['Theft', 'Suspicious Activity', 'Patrol Observation', 'Trespassing', 'Burglary Attempt'],
    Safety: ['Gas Leak', 'Electric Transformer Spark', 'Open Wire Hazard', 'Fire Alarm Trigger'],
    Utilities: ['Water Shortage', 'Street Light Failure', 'Sewerage Blockage', 'Low Gas Pressure'],
    Community: ['Noise Complaint', 'Illegal Parking Dispute', 'Pet Complaint', 'Public Nuisance'],
    Infrastructure: ['Illegal Construction', 'Road Cave-in', 'Drain Wall Collapse', 'Encroachment'],
    Traffic: ['Vehicle Incident', 'Over-speeding', 'Barrier Gate Damage', 'Wrong Way Driving'],
    Other: ['Lost Property', 'General Inquiry', 'Wildlife Sighting (Margalla Porcupine/Boar)'],
  };
  const categories: IncidentCategory[] = ['Security', 'Safety', 'Utilities', 'Community', 'Infrastructure', 'Traffic', 'Other'];
  const severities: IncidentSeverity[] = ['Critical', 'High', 'Medium', 'Low'];
  const statuses: IncidentStatus[] = ['Closed', 'Open', 'In Progress', 'Pending Authority'];
  const authoritiesList = ['Police', 'Rescue 1122', 'CDA', 'Gas Company', 'Electricity Company', 'D-12 Security Watch'];

  // Base coords for D-12
  const baseLat = 33.7300;
  const baseLng = 72.9650;

  // Generate records covering the last 60 days
  const now = new Date('2026-11-02T20:00:00');
  for (let i = 29; i <= 145; i++) {
    const daysAgo = Math.floor((i - 28) * 0.45);
    const incidentDate = new Date(now.getTime() - daysAgo * 24 * 60 * 60 * 1000);
    const dateStr = incidentDate.toISOString().split('T')[0];

    // Pick hour skewed towards evening/night (8 PM - 11 PM) as per PRD prompt example!
    const hourPool = [20, 21, 22, 23, 20, 21, 22, 19, 14, 15, 11, 8, 2, 3];
    const hour = hourPool[i % hourPool.length];
    const minute = (i * 7) % 60;
    const timeStr = `${hour.toString().padStart(2, '0')}:${minute.toString().padStart(2, '0')}`;

    // Sub-sector distribution (D-12/2 is highest concentration as per PRD prompt)
    const subSector = i % 3 === 0 ? 'D-12/2' : subSectors[i % subSectors.length];
    // Street distribution (Street 5 and Street 7 are most affected as per PRD prompt)
    const street = i % 4 === 0 ? 'Street 5' : i % 5 === 0 ? 'Street 7' : streets[i % streets.length];
    const houseNo = `House ${(i * 3) % 110 + 1}`;

    const cat = categories[i % (categories.length - (i % 2 === 0 ? 3 : 0))]; // skew towards Security/Utilities
    const possibleTypes = typesByCategory[cat];
    const incidentType = possibleTypes[i % possibleTypes.length];
    const severity: IncidentSeverity = 
      cat === 'Security' && (incidentType === 'Theft' || incidentType === 'Burglary Attempt')
        ? (i % 2 === 0 ? 'Critical' : 'High')
        : severities[i % severities.length];

    const status: IncidentStatus = daysAgo > 15 ? 'Closed' : statuses[i % statuses.length];
    const auth = authoritiesList[i % authoritiesList.length] + (i % 2 === 0 ? ', CDA' : '');

    const latOffset = ((i % 17) - 8) * 0.0012;
    const lngOffset = ((i % 19) - 9) * 0.0014;
    const lat = Number((baseLat + latOffset).toFixed(4));
    const lng = Number((baseLng + lngOffset).toFixed(4));

    dataset.push({
      id: `INC-2026-${i.toString().padStart(3, '0')}`,
      fieldDate: dateStr,
      time: timeStr,
      subSector,
      streetNo: street,
      houseNo,
      incidentType,
      briefDescription: `${incidentType} logged in ${subSector}, ${street}. Field dispatch unit notified.`,
      authorities: auth,
      mapLink: `https://maps.google.com/?q=${lat},${lng}`,
      latLong: `${lat}, ${lng}`,
      latitude: lat,
      longitude: lng,
      status,
      incidentReportWhatsApp: `[DISPATCH] Report #${i}: ${incidentType} at ${street}, ${subSector}. Unit verified on scene. Status: ${status}.`,
      transcriptUrdu: `واقعہ رپورٹ نمبر ${i}: گلی نمبر ${street.replace('Street ', '')} سیکٹر ${subSector} میں ${incidentType} کا اندراج کیا گیا۔ عملہ موقع پر موجود ہے۔`,
      address: `${houseNo}, ${street}, Sub-Sector ${subSector}, Islamabad`,
      incidentCategory: cat,
      incidentSeverity: severity,
      customFields: {
        VerifiedBy: `Supervisor-${(i % 5) + 1}`,
        SectorZone: subSector,
      },
    });
  }

  return dataset;
}
